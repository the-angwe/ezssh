//! The VT handler the parser drives: alacritty's `Term` with two sequences
//! taken over.
//!
//! - **OSC 52** goes through [`crate::osc52`] (our policy:
//!   lenient base64, size cap before decoding, reads refused, live on/off)
//!   instead of alacritty's strict decoder.
//! - **Colour queries** (OSC 4 / 10 / 11 / 12 with `?`) are answered here,
//!   with the `Term` at hand, so colours a program changed are reported
//!   back. alacritty would route them through the event listener, which
//!   cannot see the `Term` (it is called with the lock held).
//!
//! Every other `Handler` method forwards to the `Term`. The forwarding
//! block is generated from vte's trait (all 71 methods default to no-ops,
//! so a hand-written list could silently miss one); regenerate it with
//! `tools/gen_hook.py` when vte is upgraded.

use std::borrow::Cow;

