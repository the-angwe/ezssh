// Writes the Lucide icons the app uses as SVG files into ../assets/icons,
// from the lucide-react package the webview build already depends on, so
// both builds draw the same artwork (Lucide is ISC licensed; see
// assets/icons/LICENSE).
//
// Strokes are white: the app tints each icon with `Image::tint`, which
// multiplies, so one rasterisation per size serves every colour.
//
// Usage (from the repo root, after `npm --prefix ui ci`):
//   node crates/ezssh-app/tools/gen_icons.mjs
// Aliases (Trash2 → trash in 1.57) have no data of their own; list the
// target name. Add a name to ICONS (the kebab-case file name under
// lucide-react/dist/esm/icons) and to `icons.rs`, then rerun.

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ICONS = [
  'arrow-left-right', 'check', 'chevron-down', 'chevron-left', 'chevron-right', 'circle-alert',
  'circle-check', 'cloud', 'cloud-off', 'cloud-upload', 'cog', 'columns-2', 'copy', 'cpu',
  'download', 'earth', 'eye', 'eye-off', 'file', 'file-input', 'file-symlink', 'folder',
  'folder-open', 'folder-plus', 'folder-tree', 'grid-3x3', 'inbox', 'info', 'key',
  'key-round', 'key-square', 'layers', 'layout-grid', 'loader-circle', 'lock', 'maximize-2',
  'minimize-2', 'minus', 'monitor', 'monitor-dot', 'monitor-off', 'moon', 'network',
  'package-check', 'package-open', 'palette', 'panel-left-close', 'panel-left-open', 'pencil',
  'play', 'plug-zap', 'plus', 'refresh-ccw', 'refresh-cw', 'rows-2', 'save', 'server', 'settings',
  'settings-2', 'shield', 'shield-alert', 'shield-check', 'shield-x', 'slash', 'sliders-vertical',
  'sparkles', 'square', 'square-stack', 'square-terminal', 'sun', 'terminal', 'trash',
  'triangle-alert', 'type', 'upload', 'user', 'x',
];

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..', '..');
const lucide = join(repo, 'ui', 'node_modules', 'lucide-react');
const out = join(here, '..', 'assets', 'icons');

const escape = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

const pkg = JSON.parse(await readFile(join(lucide, 'package.json'), 'utf8'));
await mkdir(out, { recursive: true });
for (const name of ICONS) {
  const mod = await import(pathToFileURL(join(lucide, 'dist', 'esm', 'icons', `${name}.mjs`)).href);
  const data = mod.__iconData;
  if (!data?.node) throw new Error(`${name}: no __iconData in lucide-react ${pkg.version}`);
  const children = data.node
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== 'key')
        .map(([k, v]) => `${k}="${escape(v)}"`)
        .join(' ');
      return `  <${tag} ${a}/>`;
    })
    .join('\n');
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" ` +
    `stroke="#ffffff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n${children}\n</svg>\n`;
  await writeFile(join(out, `${name}.svg`), svg);
}
await writeFile(
  join(out, 'VERSION'),
  `lucide-react ${pkg.version}\n${ICONS.length} icons, generated by tools/gen_icons.mjs\n`,
);
console.log(`wrote ${ICONS.length} icons from lucide-react ${pkg.version} to ${out}`);
